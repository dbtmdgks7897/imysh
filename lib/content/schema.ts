import { z } from "zod";
import { LOCALES, type Locale } from "@/lib/locales";

// Closed enum: a typo in meta.yaml fails the build instead of shipping an unstyled badge.
// finished = the project ended and never ran publicly; closed = it ran publicly and has been shut down;
// paused = stopped on purpose with everything kept, to be reopened only when a real need appears.
export const PROJECT_STATUSES = ["deployed", "in-progress", "finished", "closed", "planned", "paused"] as const;
export const projectStatusSchema = z.enum(PROJECT_STATUSES);
export type ProjectStatus = z.infer<typeof projectStatusSchema>;

// All images are committed under public/images/ (generated by `npm run images`). No remote hosts.
export const imageRefSchema = z
  .string()
  .regex(/^\/images\/[a-z0-9\-/]+\.webp$/, 'image must be a generated "/images/....webp" path');

// One image for every locale, or one per locale (e.g. a diagram whose labels are in the page's language).
// A per-locale map must name every locale: no silent fallback, same rule as the text.
export const localizedImageSchema = z.union([
  imageRefSchema,
  z.strictObject(Object.fromEntries(LOCALES.map((l) => [l, imageRefSchema])) as Record<Locale, typeof imageRefSchema>),
]);
export type LocalizedImage = z.infer<typeof localizedImageSchema>;

export function imageForLocale(image: LocalizedImage | undefined, locale: Locale): string | undefined {
  if (image === undefined || typeof image === "string") return image;
  return image[locale];
}

/** Every file a localized image refers to (for validation). */
export function imageRefs(image: LocalizedImage | undefined): string[] {
  if (image === undefined) return [];
  return typeof image === "string" ? [image] : LOCALES.map((l) => image[l]);
}

export const idSchema = z.string().regex(/^[a-z0-9]+(-[a-z0-9]+)*$/, "id must be kebab-case");
export const slugPathSchema = z
  .string()
  .regex(/^[a-z0-9-]+(\/[a-z0-9-]+)*$/, 'project reference must look like "kigaru/kaouranai"');

// Detail-page sections (spec §3, template B). `tech` is folded into <details>.
export const SECTION_KEYS = ["why", "what", "tech", "thought"] as const;
export const sectionKeySchema = z.enum(SECTION_KEYS);
export type SectionKey = z.infer<typeof sectionKeySchema>;

export const projectMetaSchema = z.strictObject({
  period: z.string().min(1),
  stack: z.array(z.string().min(1)),
  status: projectStatusSchema,
  order: z.number().int().optional(),
  thumbnail: localizedImageSchema.optional(),
  hero: localizedImageSchema.optional(), // large image at the top of the detail page
  // "contain" for diagrams whose edges carry text; photos and screenshots keep the default crop.
  heroFit: z.enum(["cover", "contain"]).optional(),
  // One entry per h2 in {ja,ko}.md, in order: maps the markdown onto the fixed sections
  // without rewriting its words. Several h2s may share a key.
  sections: z.array(sectionKeySchema).min(1),
  links: z
    .strictObject({
      github: z.url().optional(),
      live: z.url().optional(),
    })
    .default({}),
});
/** meta.yaml as written: images may be per-locale maps. */
export type ProjectMetaSource = z.infer<typeof projectMetaSchema>;
/** meta.yaml resolved for one locale: images are plain paths. */
export type ProjectMeta = Omit<ProjectMetaSource, "thumbnail" | "hero"> & { thumbnail?: string; hero?: string };

// Per-locale frontmatter carries sentences only; everything structural is in meta.yaml.
export const projectFrontmatterSchema = z.strictObject({
  title: z.string().min(1),
  summary: z.string().min(1),
  role: z.string().min(1).optional(), // 立場 — only when the sources state it
  heroAlt: z.string().min(1).optional(), // alt text for meta.yaml `hero` when the image carries meaning
});

// ---- now (spec §3.1, §5) ----

export const nowSchema = z.strictObject({
  asOf: z.string().min(1),
  portrait: imageRefSchema.nullable(),
  cards: z.array(
    z.strictObject({
      id: idSchema,
      image: imageRefSchema.nullable(),
      project: slugPathSchema.nullable(), // internal project page, if any
      href: z.url().nullable(), // external link, if any
    }),
  ),
  oneLiners: z.array(z.strictObject({ id: idSchema, since: z.string().min(1) })),
});
export type Now = z.infer<typeof nowSchema>;

export const nowTextSchema = z.strictObject({
  statement: z.strictObject({
    before: z.string().min(1),
    accent: z.string().min(1), // the one accented phrase
    after: z.string().min(1),
  }),
  thinking: z.array(z.string().min(1)).min(1).max(2),
  cards: z.record(
    z.string(),
    z.strictObject({ label: z.string().min(1), title: z.string().min(1), text: z.string().min(1) }),
  ),
  oneLiners: z.record(z.string(), z.string().min(1)),
});
export type NowText = z.infer<typeof nowTextSchema>;

// ---- path (spec §3.2, §5) ----

const pathChildSchema = z.strictObject({
  id: idSchema,
  photos: z.array(imageRefSchema).default([]),
  projects: z.array(slugPathSchema).default([]),
});
export type PathChild = z.infer<typeof pathChildSchema>;

const pathNodeSchema = z.strictObject({
  id: idSchema,
  period: z.string().min(1),
  current: z.boolean().default(false), // the row that links back to "now"
  photos: z.array(imageRefSchema).default([]),
  projects: z.array(slugPathSchema).default([]),
  children: z.array(pathChildSchema).default([]),
});
export type PathNode = z.infer<typeof pathNodeSchema>;

export const pathSchema = z.strictObject({ nodes: z.array(pathNodeSchema).min(1) });
export type PathData = z.infer<typeof pathSchema>;

export const pathTextSchema = z.strictObject({
  heading: z.string().min(1),
  nodes: z.record(
    z.string(),
    z.strictObject({
      label: z.string().min(1), // year cell, e.g. "2026 前半"
      doing: z.string().min(1),
      thought: z.string().min(1),
      thoughtNote: z.string().min(1).optional(),
      photoAlts: z.array(z.string().min(1)).optional(), // one per path.yaml photo, same order
      next: z.string().min(1).optional(), // "why I moved on"; required except on the current node
    }),
  ),
});
export type PathText = z.infer<typeof pathTextSchema>;
